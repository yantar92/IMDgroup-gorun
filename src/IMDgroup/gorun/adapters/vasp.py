class VaspAdapter:
    """``gorun vasp`` backend."""

    name = "vasp"
    log_file = "vasp.out"

    def __init__(
        self, *,
        vasp_variant: str = "ncl",
        no_incar_py: bool = False,
        no_vasp_config: bool = False,
        no_clean: bool = False,
        incar_mods: dict[str, str] | None = None,
    ) -> None:
        self.vasp_variant = vasp_variant
        self.no_incar_py = no_incar_py
        self.no_vasp_config = no_vasp_config
        self.no_clean = no_clean
        self.incar_mods = incar_mods

    # ------------------------------------------------------------------
    # Environment
    # ------------------------------------------------------------------

    def validate_environment(self) -> None:
        """Require ``VASP_PATH`` and ``VASP_PP_PATH``."""
        missing = []
        for var in ("VASP_PATH", "VASP_PP_PATH"):
            if var not in os.environ:
                missing.append(var)
        if missing:
            raise OSError(
                f"Required environment variables not set: {', '.join(missing)}"
            )

    # ------------------------------------------------------------------
    # Directory inspection
    # ------------------------------------------------------------------

    def is_valid_input(self, path: Path) -> bool:
        return (path / "INCAR").is_file()

    def is_converged(self, path: Path) -> bool:
        """True when converged and no INCAR chains remain.

        INCAR chains mean the job is not truly finished -- there are
        more INCAR variants to try.
        """
        if not directory_converged_p(str(path)):
            return False
        # MD runs never chain.
        if mdp(str(path)):
            return True
        # Converged, but more INCARs to process?  Then not done.
        if _has_incar_chain(path):
            return False
        return True

    def has_previous_output(self, path: Path) -> bool:
        """True when VASP output or INCAR.py exists.

        Matches the original backup condition in gorun.py.
        """
        if not self.no_incar_py and (path / "INCAR.py").is_file():
            return True
        return directory_contains_vasp_outputp(str(path))

    # ------------------------------------------------------------------
    # Preparation
    # ------------------------------------------------------------------

    def prepare_inputs(
        self,
        path: Path, *,
        keep: set[str] | None = None,
        force: bool = False,
        **kwargs,
    ) -> None:
        if keep is None:
            keep = set()

        _clear_useless_files(path)

        # -- INCAR chain rotation --
        if not mdp(str(path)) and not force:
            _rotate_incar_chain(path)

        # -- INCAR modification --
        if self.incar_mods:
            _modify_incar(path, self.incar_mods)

        # -- Main preparation (single directory) --
        self._prepare_single(path, keep)

        # -- NEB subdirectories --
        if nebp(str(path)):
            for entry in sorted(path.iterdir()):
                if entry.is_dir() and re.match(r"[0-9]+", entry.name):
                    self._prepare_single(entry, keep)
            if not self.no_clean:
                for entry in sorted(path.iterdir()):
                    if entry.is_dir() and re.match(r"[0-9]+", entry.name):
                        clear_slurm_logs(str(entry))

    def _prepare_single(self, path: Path, keep: set[str]) -> None:
        """Prepare one VASP directory (main or NEB sub)."""
        check_incar(str(path))

        # CONTCAR → POSCAR
        poscar = path / "POSCAR"
        if "POSCAR" in keep and poscar.is_file():
            print(f"Keeping existing POSCAR")
        elif "POSCAR" in keep:
            print(
                "--keep POSCAR requested but POSCAR does not exist.  "
                "Copying CONTCAR if available."
            )
            contcar_to_poscar(str(path))
        else:
            contcar_to_poscar(str(path))

        # Clean input files
        clean_vasp_inputs(str(path))

        # POTCAR
        maybe_regenerate(
            path, "POTCAR", keep,
            regenerate=lambda: _regenerate_potcar(str(path)),
        )

        # vdW kernel
        put_vdw_kernel(str(path))

        # Clear old outputs
        clear_vasp_outputs(str(path))

    # ------------------------------------------------------------------
    # Script generation
    # ------------------------------------------------------------------

    def setup_commands(self, server_config: dict) -> str:
        """Extract VASP module setup from config.

        Looks for ``server_config["vasp"]["setup"]`` first,
        then falls back to the legacy ``server_config["VASP-setup"]`` key.
        """
        if self.no_vasp_config:
            return ""

        vasp_cfg = server_config.get(self.name, {})
        if vasp_cfg:
            return vasp_cfg.get("setup", "")
        # Legacy flat config
        return server_config.get("VASP-setup", "")

    def generate_run_commands(self, path: Path, server_config: dict) -> str:
        if not self.no_incar_py and (path / "INCAR.py").is_file():
            return self._incar_py_script(path)
        return self._direct_vasp_script(server_config)

    def _direct_vasp_script(self, server_config: dict) -> str:
        """``<mpiexec> vasp_<variant>`` invocation.

        The launcher comes from ``server_config["mpiexec"]``,
        defaulting to ``mpiexec`` (LUMI sets ``srun``).  The full
        command is exported as ``VASP_COMMAND`` and then invoked,
        mirroring the legacy gorun script.
        """
        vasp_binary = os.path.join(
            os.environ["VASP_PATH"], "bin", f"vasp_{self.vasp_variant}"
        )
        mpiexec = server_config.get("mpiexec", "mpiexec")
        return (
            f'export VASP_COMMAND="{mpiexec} {vasp_binary}"\n'
            "$VASP_COMMAND"
        )

    def _incar_py_script(self, path: Path) -> str:
        """ASE-wrapped script when INCAR.py is present."""
        print(
            colored(
                "Found INCAR.py.  Using instead of directly running VASP.",
                "yellow",
            )
        )
        return (
            'export VASP_COMMAND="gorun vasp --local --no-incar-py --force '
            '--no-clean --keep POSCAR"\n'
            "python <<EOF\n"
            f"{_PYTHON_HEADER}\n"
            f"$(cat INCAR.py)\n"
            f"{_PYTHON_FINALIZER}\n"
            "EOF"
        )

    # ------------------------------------------------------------------
    # Backup excludes
    # ------------------------------------------------------------------

    def backup_excludes(self) -> list[str]:
        return ["WAVECAR"]


