def _has_incar_chain(path: Path) -> bool:
    """Return True when ``INCAR.{0,1,2,...}`` files exist."""
    return bool(sorted(path.glob("INCAR.[0-9]*")))


def _rotate_incar_chain(path: Path) -> None:
    """If converged with remaining INCAR chains, rotate the first one in."""
    if not directory_converged_p(str(path)):
        return
    chains = sorted(path.glob("INCAR.[0-9]*"))
    if not chains:
        return
    print(
        colored(
            f"Converged, but found additional INCARs: {chains}.  "
            f"Replacing INCAR with {chains[0]}",
            "yellow",
        )
    )
    incar = path / "INCAR"
    incar.rename(path / "INCAR.old")
    chains[0].rename(incar)


def _modify_incar(path: Path, mods: dict[str, str]) -> None:
    """Apply key=value modifications to INCAR."""
    from pymatgen.io.vasp.inputs import Incar

    incar_path = path / "INCAR"
    incar = Incar.from_file(str(incar_path))
    incar_before = incar.copy()

    for key, val in mods.items():
        if val == "None":
            incar.pop(key, None)
        else:
            incar[key] = val

    incar.write_file(str(incar_path))
    incar_diff = incar_before.diff(incar).get("Different")
    if incar_diff is not None and len(incar_diff) > 0:
        print(colored(f"Changed INCAR: {incar_diff}", "yellow"))
    else:
        print(colored("Leaving INCAR unchanged", "yellow"))


def _clear_useless_files(path: Path) -> None:
    """Clear empty CHG, CHGCAR, REPORT, WAVECAR if we are about to re-run."""
    if directory_contains_vasp_outputp(str(path)) or (
        (path / "INCAR.py").is_file()
    ):
        clear_useless_vasp_files(str(path))


def _regenerate_potcar(dir_path: str) -> None:
    """Call ``generate_potcar`` with ``keep_existing=False``."""
    generate_potcar(dir_path, keep_existing=False)
